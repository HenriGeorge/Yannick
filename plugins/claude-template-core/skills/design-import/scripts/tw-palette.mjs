export function twColor(name) {
  if (!name) return null;
  if (name === "white") return P.white._;
  if (name === "black") return P.black._;
  const m = name.match(/^([a-z]+)-(\d{2,3})$/);
  if (!m) return null;
  const [, fam, step] = m;
  return P[fam]?.[Number(step)] ?? null;
}

